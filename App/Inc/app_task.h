#ifndef APP_TASK_H
#define APP_TASK_H

#include <stdint.h>

/* ============================================================
 * App 层：整车业务流程
 * 可以同时调用 Bsp 层和 Alg 层；Bsp 层不能反过来调这里。
 * ============================================================ */

/* ------------------------------------------------------------------
 * vision_stage_task：视觉阶段状态机
 *   输入：chassis_state —— 底盘组给的"到隧道前"状态量
 *   作用：底盘到隧道前（==2）时，把 g_vision_stage 从 1 切到 2，
 *         并连发 3 次通知视觉切换模型（只发一次，之后不再发）
 * ------------------------------------------------------------------ */
void vision_stage_task(uint8_t chassis_state);

/* ------------------------------------------------------------------
 * app_task_10ms：整车 10ms 周期任务总入口
 *   所有周期性业务任务都在这里按顺序调用。
 *   现在  —— main.c 的 while(1) 里：app_task_10ms(); HAL_Delay(10);
 *   以后  —— 加电机后改成 TIM 中断每 10ms 调一次，函数体不用改
 * ------------------------------------------------------------------ */
void app_task_10ms(void);

#endif